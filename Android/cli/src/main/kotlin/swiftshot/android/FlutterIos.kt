package swiftshot.android

import swiftshot.android.shared.Json
import java.io.File

/**
 * Flutter on iPhones and iPads exactly as on a device: the project's Flutter bundle, built for the
 * simulator with Swiftshot's entry point, in a small SwiftUI host app with a `#Preview` per
 * Flutter preview (each a FlutterViewController running that preview), rendered by the iOS
 * renderer without booting a simulator. Text goes through Core Text (SF's optical sizes and
 * tracking), pixels through Impeller on Metal, and the status bar is the system's.
 */
class FlutterIos(private val o: Options, private val log: Log, private val root: File, private val dir: File, private val sdk: File, private val output: File) {
    private val ios = Ios(o, log, output)

    /** Why the exact iOS renderer can't run here, or null when it can. */
    fun unavailable(): String? = when {
        !Host.mac -> "not a Mac"
        !ios.available -> "the iOS renderer (swiftshot) or Xcode is missing"
        !File(root, "ios/Runner.xcodeproj").isDirectory -> "the project has no ios/ folder (flutter create --platforms ios .)"
        else -> null
    }

    data class Shot(val file: String, val preview: String, val device: String, val language: String, val appearance: String, val width: Int, val height: Int)

    /**
     * [manifest]: the previews by index; [measured]: the size in points headless rendering gave
     * the components that size themselves (an infinite width or height).
     */
    fun run(manifest: List<Map<*, *>>, measured: Map<String, Pair<Double, Double>>, devices: List<String>): List<Shot>? {
        val main = File(dir, "swiftshot_ios_main.dart")
        main.writeText(
            """
            // Generated by Swiftshot: the entry point of its iOS host app (one preview per engine, by index).
            import 'swiftshot_flutter.dart' as swiftshot;
            import 'swiftshot_entries.dart';

            void main(List<String> args) {
              setUp();
              swiftshot.runPreview(entries(), args);
            }
            """.trimIndent() + "\n"
        )
        val runnerApp = File(root, "build/ios/iphonesimulator/Runner.app")
        val stampFile = File(dir, "ios/build.stamp")
        val stamp = buildStamp()
        if (runnerApp.isDirectory && stampFile.isFile && stampFile.readText() == stamp) {
            log.step("The Flutter app for the iOS simulator is up to date")
        } else {
            if (!buildApp(main)) return null
            stampFile.parentFile.mkdirs()
            stampFile.writeText(buildStamp())
        }
        return render(runnerApp, manifest, measured, devices)
    }

    /**
     * What the simulator build depends on: the project's files (path, size, modification time;
     * build outputs left out), the generated Dart files' contents and the SDK's version.
     */
    private fun buildStamp(): String {
        val skip = setOf("build", ".dart_tool", ".git", "Pods", ".gradle", ".idea", "screenshots", "android")
        val digest = java.security.MessageDigest.getInstance("SHA-256")
        // Files flutter pub get and flutter build rewrite on every run, unchanged.
        val generated = setOf("Generated.xcconfig", "flutter_export_environment.sh", ".flutter-plugins", ".flutter-plugins-dependencies", ".DS_Store")
        root.walkTopDown().onEnter { it == root || it.name !in skip }.filter { it.isFile && it.name !in generated }.sortedBy { it.path }.forEach { f ->
            digest.update("${f.relativeTo(root).path}\u0000${f.length()}\u0000${f.lastModified()}\n".toByteArray())
        }
        dir.listFiles { f -> f.extension == "dart" }.orEmpty().sortedBy { it.name }.forEach { digest.update(it.readBytes()) }
        File(sdk, "version").takeIf { it.isFile }?.let { digest.update(it.readBytes()) }
        File(sdk, "bin/cache/engine.stamp").takeIf { it.isFile }?.let { digest.update(it.readBytes()) }
        return digest.digest().joinToString("") { "%02x".format(it) }
    }

    private fun buildApp(main: File): Boolean {
        log.step("Building the Flutter app for the iOS simulator")
        val build = ProcessBuilder(File(sdk, "bin/flutter").path, "build", "ios", "--simulator", "--debug", "--no-pub", "-t", main.relativeTo(root).path)
            .directory(root).redirectErrorStream(true).also { it.environment()["FLUTTER_ROOT"] = sdk.path }.start()
        val buildOut = build.inputStream.bufferedReader().readText()
        if (build.waitFor() != 0) {
            log.warn("iOS: flutter build ios --simulator failed; iPhones and iPads are rendered headless instead:\n" + buildOut.lines().filter { it.isNotBlank() }.takeLast(15).joinToString("\n"))
            return false
        }
        return true
    }

    private fun render(runner: File, manifest: List<Map<*, *>>, measured: Map<String, Pair<Double, Double>>, devices: List<String>): List<Shot>? {
        val app = hostApp(runner, manifest, measured) ?: return null
        val iosOut = File(output, ".flutter-ios")
        // A pinned brightness or locale renders once, as headless (Dart decides the rest itself).
        val rules = manifest.flatMap { p ->
            val name = p["name"] as String
            listOfNotNull(
                (p["brightness"] as String?)?.let { "--screen" to "$name: appearances=$it" },
                (p["locale"] as String?)?.let { l -> "--screen" to "$name: languages=${if (l in o.languages) l else o.languages.first()}" },
            )
        }.flatMap { listOf(it.first, it.second) }
        val (status, shots) = ios.renderApp(app, devices, iosOut, rules)
        val pinned = manifest.associate { (it["name"] as String) to (it["brightness"] != null) }
        val result = shots.map { s ->
            val name = s["preview"] as String
            val appearance = s["appearance"] as String? ?: "light"
            val suffix = if (pinned[name] != true && (o.appearances.size > 1 || appearance == "dark")) "-$appearance" else ""
            val rel = "${s["language"]}/${clean(s["device"] as String)}-${clean(name)}$suffix.png"
            File(output, rel).parentFile.mkdirs()
            File(iosOut, s["file"] as String).copyTo(File(output, rel), overwrite = true)
            Shot(rel, name, s["device"] as String, s["language"] as String, appearance, (s["width"] as Number?)?.toInt() ?: 0, (s["height"] as Number?)?.toInt() ?: 0)
        }
        iosOut.deleteRecursively()
        if (status != 0) log.warn("iOS: some screenshots failed (exit $status)")
        return result
    }

    private fun clean(s: String) = s.replace('/', '-').replace(':', '-')

    /** SwiftshotHost.app: Runner's frameworks (Flutter, the app bundle, plugins) and a #Preview per preview. */
    private fun hostApp(runner: File, manifest: List<Map<*, *>>, measured: Map<String, Pair<Double, Double>>): File? {
        val build = File(dir, "ios").apply { mkdirs() }
        val app = File(build, "SwiftshotHost.app")
        val frameworks = File(app, "Frameworks")
        frameworks.deleteRecursively()
        File(runner, "Frameworks").copyRecursively(frameworks, overwrite = true)
        val localizations = o.languages.flatMap { listOf(it.replace('_', '-'), it.substringBefore('-').substringBefore('_')) }.distinct().joinToString("") { "<string>$it</string>" }
        File(app, "Info.plist").writeText(Ios.INFO_PLIST.replace("</dict></plist>", "<key>CFBundleLocalizations</key><array>$localizations</array>\n</dict></plist>"))
        val registrant = File(root, "ios/Runner/GeneratedPluginRegistrant.m").takeIf { it.isFile }
        val swift = hostMain(manifest, measured, registrant != null)
        val mainFile = File(build, "main.swift")
        val binary = File(app, "SwiftshotHost")
        val stamp = File(build, "registrant.stamp")
        val registrantText = registrant?.readText().orEmpty()
        if (!binary.isFile || !mainFile.isFile || mainFile.readText() != swift || (stamp.takeIf { it.isFile }?.readText() ?: "") != registrantText) {
            mainFile.writeText(swift)
            log.step("Building the iOS host app")
            val objects = mutableListOf<String>()
            if (registrant != null) {
                // The project's plugins, registered as Runner registers them.
                val obj = File(build, "GeneratedPluginRegistrant.o")
                sh(listOf("xcrun", "-sdk", "iphonesimulator", "clang", "-c", "-target", "arm64-apple-ios17.0-simulator", "-fobjc-arc", "-fmodules",
                    "-F", frameworks.path, "-I", registrant.parentFile.path, registrant.path, "-o", obj.path), "compiling the plugin registrant") ?: return null
                objects += obj.path
            }
            val plugins = frameworks.listFiles().orEmpty().filter { it.name.endsWith(".framework") && it.name != "App.framework" }
                .flatMap { listOf("-framework", it.name.removeSuffix(".framework")) }
            sh(listOf("xcrun", "-sdk", "iphonesimulator", "swiftc", "-target", "arm64-apple-ios17.0-simulator", "-Onone", "-module-name", "SwiftshotHostApp",
                "-F", frameworks.path) + plugins + listOf("-Xlinker", "-rpath", "-Xlinker", "@executable_path/Frameworks", mainFile.path) + objects +
                listOf("-o", binary.path), "building the iOS host app") ?: return null
            stamp.writeText(registrantText)
        }
        sh(listOf("codesign", "-f", "-s", "-", app.path), "signing the iOS host app") ?: return null
        return app
    }

    internal fun hostMain(manifest: List<Map<*, *>>, measured: Map<String, Pair<Double, Double>>, plugins: Boolean): String = buildString {
        appendLine("// Generated by Swiftshot: a #Preview per Flutter preview, each a Flutter engine running Swiftshot's entry point.")
        appendLine("import SwiftUI")
        appendLine("import Flutter")
        appendLine()
        appendLine("@_cdecl(\"swiftshot_host_main\") public func swiftshotHostMain() {}")
        appendLine()
        appendLine("/// A fresh engine per screenshot, as an app launch has, spawned from one engine group: spawned")
        appendLine("/// engines share the Dart isolate group, so they start in milliseconds.")
        appendLine("nonisolated(unsafe) let group = FlutterEngineGroup(name: \"swiftshot\", project: nil)")
        appendLine()
        appendLine("@MainActor func flutterPreview(_ index: Int) -> UIViewController {")
        appendLine("    let options = FlutterEngineGroupOptions()")
        appendLine("    options.entrypointArgs = [String(index)]")
        appendLine("    let engine = group.makeEngine(with: options)")
        if (plugins) appendLine("    (NSClassFromString(\"GeneratedPluginRegistrant\") as? NSObject.Type)?.perform(NSSelectorFromString(\"registerWithRegistry:\"), with: engine)")
        appendLine("    return FlutterViewController(engine: engine, nibName: nil, bundle: nil)")
        appendLine("}")
        appendLine()
        appendLine("struct SwiftshotHostApp: App { var body: some Scene { WindowGroup { Color.clear } } }")
        appendLine()
        manifest.forEachIndexed { i, p ->
            val name = (p["name"] as String).replace("\\", "\\\\").replace("\"", "\\\"")
            // Components at their size in points: as declared, else as headless rendering measured it.
            val traits = if (p["component"] == true) {
                val m = measured[p["name"] as String]
                val w = (p["width"] as Number?)?.toDouble() ?: m?.first
                val h = (p["height"] as Number?)?.toDouble() ?: m?.second
                if (w != null && h != null) ", traits: .fixedLayout(width: ${fmt(w)}, height: ${fmt(h)})" else ", traits: .sizeThatFitsLayout"
            } else ""
            appendLine("#Preview(\"$name\"$traits) { flutterPreview($i) }")
        }
        appendLine()
        appendLine("if let start = dlsym(UnsafeMutableRawPointer(bitPattern: -2), \"SwiftshotAgentStartNow\") { unsafeBitCast(start, to: (@convention(c) () -> Void).self)() }")
        appendLine("SwiftshotHostApp.main()")
    }

    private fun fmt(v: Double) = if (v % 1.0 == 0.0) v.toInt().toString() else "%.2f".format(java.util.Locale.ROOT, v)

    private fun sh(cmd: List<String>, what: String): Unit? {
        val p = ProcessBuilder(cmd).redirectErrorStream(true).start()
        val out = p.inputStream.bufferedReader().readText()
        if (p.waitFor() == 0) return Unit
        log.warn("iOS: failed $what; iPhones and iPads are rendered headless instead:\n${out.trim().lines().takeLast(20).joinToString("\n")}")
        return null
    }
}
